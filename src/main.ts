function bytes(value: number): string {
  if (value >= 1024 ** 3) return `${(value / 1024 ** 3).toLocaleString(undefined, { maximumFractionDigits: 2 })} GiB`
  if (value >= 1024 ** 2) return `${(value / 1024 ** 2).toLocaleString(undefined, { maximumFractionDigits: 2 })} MiB`
  if (value >= 1024) return `${(value / 1024).toLocaleString(undefined, { maximumFractionDigits: 2 })} KiB`
  return `${value.toLocaleString()} B`
}

function duration(value: number | null): string {
  if (value === null) return '—'
  return value >= 1000 ? `${(value / 1000).toLocaleString(undefined, { maximumFractionDigits: 3 })} s`
    : `${value.toLocaleString(undefined, { maximumFractionDigits: 2 })} ms`
}

function rate(count: number, milliseconds: number): string {
  return milliseconds > 0 ? `${(count / 1048576 / (milliseconds / 1000)).toLocaleString(undefined, { maximumFractionDigits: 2 })} MiB/s` : '—'
}

