form.addEventListener('submit', async (event) => {
  event.preventDefault()
  updateSettings()
  if (startButton.disabled || !settings) return
  const runSettings = { ...settings }
  running = true
  stopRequested = false
  controller = new AbortController()
  activeRunId = undefined
  recent = []
  passedFiles = uploadedBytes = downloadedBytes = uploadMs = downloadMs = 0
  expectedFiles = runSettings.fileCount * runSettings.rounds
  lastProgress = undefined
  lastAnnouncement = 0
  message('app-error', '')
  message('run-outcome', '')
  element('run-statistics').hidden = true
  element('metric-wall').textContent = 'Running…'
  element('phase-times').textContent = 'Preparing device. Capability probing, generation and hash work are outside the transfer timers.'
  element('progress-description').textContent = 'Starting a new run and opening its local report…'
  badge('run-badge', 'Preparing', 'active')
  progressBar.value = 0
  progressBar.max = expectedFiles
  updateLive()
  updateControls()
  let payloads: PayloadService | undefined
  try {
    payloads = createPayloadService()
    const summary = await runWorkload({
      device: client, settings: runSettings, environment, payloads, signal: controller.signal,
      onStart: async (summary) => {
        await store.start(summary)
        activeRunId = summary.id
      },
      onFile: async (result) => {
        await store.appendFile(result)
        recent.push(result)
        if (recent.length > RECENT_FILES) recent.shift()
        passedFiles += Number(result.passed)
        uploadedBytes += result.uploadedBytes
        downloadedBytes += result.downloadedBytes
        uploadMs += result.uploadMs
        downloadMs += result.downloadMs
        scheduleLive()
      },
      onProgress: (progress) => {
        lastProgress = progress
        scheduleLive()
      },
    })
    controller = undefined
    updateControls()
    await store.finish(summary)
    if (renderTimer !== undefined) clearTimeout(renderTimer)
    renderTimer = undefined
    lastProgress = undefined
    passedFiles = summary.completedFiles
    uploadedBytes = summary.totals.uploadedBytes
    downloadedBytes = summary.totals.downloadedBytes
    uploadMs = summary.totals.uploadMs
    downloadMs = summary.totals.downloadMs
    updateLive()
    progressBar.value = summary.completedFiles
    element('metric-wall').textContent = duration(summary.totals.wallMs)
    badge('run-badge', summary.status === 'completed' ? 'Completed · verified' : summary.status === 'canceled' ? 'Canceled · partial' : 'Failed · partial', summary.status === 'completed' ? 'success' : 'warning')
    const description = `${summary.completedFiles.toLocaleString()} of ${summary.expectedFiles.toLocaleString()} files verified. ${summary.status === 'completed' ? 'Generated test files cleaned up.' : 'This is a partial report, not a complete performance result.'}`
    element('progress-description').textContent = description
    element('progress-announcement').textContent = `${summary.status}. ${description}`
    element('phase-times').textContent = `Setup ${duration(summary.totals.setupMs)} · Generation / expected SHA-256 ${duration(summary.totals.prepareMs)} · Verification / size checks ${duration(summary.totals.verifyMs)} · Cleanup ${duration(summary.totals.cleanupMs)}`
    const outcome = element('run-outcome')
    outcome.className = `notice ${summary.status === 'completed' ? 'success-notice' : 'warning'}`
    message('run-outcome', `Run ${summary.id}. ${summary.error ?? 'Run finished and saved locally.'}${summary.leftovers.length ? ` Cleanup pending: ${summary.leftovers.join(', ')}. Reconnect the same phone before retrying cleanup.` : ''}`)
    if (summary.error?.includes('Local report storage failed')) {
      storageReady = false
      message('storage-error', summary.error)
    } else {
      renderStatistics(element('run-statistics'), await store.stats(summary.id))
    }
    await refreshReports()
  } catch (error) {
    if (renderTimer !== undefined) clearTimeout(renderTimer)
    diagnosticError('app.run.failed', 'Run or report finalization failed. Keep the diagnostic log and committed partial report.',
      error, { runId: activeRunId })
    renderTimer = undefined
    lastProgress = undefined
    badge('run-badge', 'Failed · partial', 'warning')
    element('metric-wall').textContent = 'Not finalized'
    element('progress-description').textContent = 'The run could not complete. Any committed file records remain in local storage.'
    message('app-error', errorMessage(error))
    if (/storage|IndexedDB|quota/iu.test(errorMessage(error))) {
      storageReady = false
      message('storage-error', errorMessage(error))
    }
    try { await refreshReports() } catch (refreshError) {
      diagnosticError('app.reports.refresh.failed', 'Partial reports could not be refreshed. The original run error remains visible.',
        refreshError, { runId: activeRunId })
    }
  } finally {
    payloads?.dispose()
    running = false
    controller = undefined
    activeRunId = undefined
    stopRequested = false
    if (!client.connected) setConnection('Disconnected', 'Reconnect the phone before another run. Review any recorded leftover test files.')
    updateControls()
  }
})

